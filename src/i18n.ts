export function getInitialLanguage(): Language {
  try {
    const saved = localStorage.getItem(languageKey)
    if (isLanguage(saved)) return saved
  } catch {
    // Browser preferences are still available when storage is restricted.
  }
  for (const preference of globalThis.navigator?.languages ?? []) {
    const match = preference.toLowerCase().match(/^(zh|ja|en)/)?.[1]
    if (isLanguage(match)) return match
  }
  return 'ja'
}

export function persistLanguage(language: Language): void {
  document.documentElement.lang = documentLanguages[language]
  try { localStorage.setItem(languageKey, language) } catch {}
}

export function useMessages() {
  return messages[useContext(LanguageContext)]
}

export function actionError(reason: unknown, language: Language): string {
  if (!(reason instanceof Error)) return messages[language].failed
  return language === 'ja' ? reason.message : actionErrors.get(reason.message)?.[language] ?? reason.message
}
